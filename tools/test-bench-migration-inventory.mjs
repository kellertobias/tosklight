#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "docs/engineering/test-bench-migration-inventory.md");
const playwright = path.join(root, "apps/control-ui/node_modules/.bin/playwright");
const report = JSON.parse(execFileSync(playwright, [
	"test",
	"--config",
	path.join(root, "playwright.config.ts"),
	"--list",
	"--reporter=json",
], { cwd: path.join(root, "apps/control-ui"), encoding: "utf8" }));

const rows = [];
for (const suite of report.suites) {
	if (!suite.file || suite.file.includes("/")) continue;
	const source = fs.readFileSync(path.join(root, "tests", suite.file), "utf8");
	collect(suite, {
		file: suite.file,
		contract: "repository contract",
		migrated: source.includes("@bench-semantic-world"),
	});
}

function collect(suite, context) {
	const contract = suite.title.startsWith("docs/")
		? suite.title
		: context.contract;
	for (const spec of suite.specs ?? []) {
		const surfaces = spec.tags?.length
			? spec.tags.map((tag) => `@${tag}`).join(" ")
			: tagsIn(spec.title);
		rows.push({
			file: context.file,
			title: spec.title,
			contract,
			surfaces,
			family: helperFamily(context.file),
			artifacts: artifactContract(context.file),
			constraint: executionConstraint(context.file),
			status: migrationStatus(surfaces, context.migrated),
		});
	}
	for (const child of suite.suites ?? [])
		collect(child, { ...context, contract });
}

const ignoredEntrypoints = [
	["02-help-screenshots.spec.ts", "serial generated screenshots", "generated-boundary"],
	["visual-recording.spec.ts", "serial video catalog assembly", "generated-boundary"],
];

const markdown = `# Test-bench migration inventory

Generated by \`node tools/test-bench-migration-inventory.mjs --write\`.
Do not edit the case table by hand. The architecture gate runs this generator in
\`--check\` mode, so every default-catalog root case must remain represented.

Status meanings:

- \`pending-semantic-migration\`: operator-facing UI still needs conversion in 10b/10c.
- \`reviewed-low-level-boundary\`: API, OSC, wire, restart, desktop, or bench mechanics
  are themselves part of the acceptance contract.
- \`generated-boundary\`: intentionally excluded from the default catalog and kept serial.

Default catalog: **${rows.length} root cases across ${new Set(rows.map((row) => row.file)).size} files**.

| Source | Scenario and intent | Contract | Surfaces | Helper family | Artifacts | Constraint | Status |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.map((row) => `| ${cell(row.file)} | ${cell(row.title)} | ${cell(row.contract)} | ${cell(row.surfaces)} | ${cell(row.family)} | ${cell(row.artifacts)} | ${cell(row.constraint)} | ${cell(row.status)} |`).join("\n")}

## Serial generated entrypoints

| Source | Constraint | Status |
| --- | --- | --- |
${ignoredEntrypoints.map((row) => `| ${row.map(cell).join(" | ")} |`).join("\n")}

## Helper classifications

| Current helper family | Classification | Migration rule |
| --- | --- | --- |
| \`apps/control-ui/e2e/bench/**/*Scenario.ts\` adapters | keep internal | Public semantic world delegates to these; scenario files do not import them directly. |
| Normalized assertion/oracle modules under \`tests/support\` | wrap temporarily | Keep shared state and wire assertions while operator actions move to semantic helpers. |
| Root-spec Page/Locator, ApiDriver, and raw transport helpers | replace | Add or improve a public semantic helper, then mark the migrated root spec \`${semanticMarker()}\`. |
| CSS/pane-id, coordinate, fixture-UUID, encoder-slot, and mutable show-object helpers | remove after final consumer | Do not reproduce them in migrated scenarios; delete only after repository search proves no consumers. |
`;

if (process.argv.includes("--write")) {
	fs.writeFileSync(output, markdown);
	console.log(`Wrote ${path.relative(root, output)} (${rows.length} cases).`);
} else if (process.argv.includes("--check")) {
	const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
	if (current !== markdown) {
		console.error("Test-bench migration inventory is stale; run node tools/test-bench-migration-inventory.mjs --write");
		process.exitCode = 1;
	} else {
		console.log(`Test-bench migration inventory covers ${rows.length} root cases.`);
	}
} else {
	process.stdout.write(markdown);
}

function tagsIn(title) {
	return [...title.matchAll(/(^|\s)(@[a-z-]+)/gu)].map((match) => match[2]).join(" ");
}

function migrationStatus(surfaces, migrated) {
	if (migrated) return "migrated-semantic-world";
	return surfaces.includes("@ui")
		? "pending-semantic-migration"
		: "reviewed-low-level-boundary";
}

function helperFamily(file) {
	return file.replace(/^\d+-/u, "").replace(/\.spec\.ts$/u, "");
}

function artifactContract(file) {
	if (/generate-show|product-demo/u.test(file)) return "generated show/video";
	if (/help-screenshot/u.test(file)) return "help screenshots";
	return "standard failure evidence";
}

function executionConstraint(file) {
	if (/generate-show|help-screenshot|product-demo|visual-recording/u.test(file))
		return "serial";
	if (/desktop-process/u.test(file)) return "macOS desktop";
	return "parallel";
}

function cell(value) {
	return String(value || "none")
		.replaceAll("|", "\\|")
		.replaceAll("\n", " ");
}

function semanticMarker() {
	return "// @bench-semantic-world";
}
