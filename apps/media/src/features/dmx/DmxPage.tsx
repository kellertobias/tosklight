function ConsolePatch({ output }: { output: OutputView }) {
	const map = useDmxMap(output.id);
	const blocks = new Map<string, number[]>();
	for (const channel of map.data?.channels ?? []) {
		const label =
			channel.group.kind === "layer"
				? `Layer ${channel.group.number}`
				: "Master";
		const addresses = blocks.get(label) ?? [];
		addresses.push(channel.absoluteChannel);
		blocks.set(label, addresses);
	}
	return (
		<section aria-label={`${output.name} console patch`}>
			<h4>{output.name}</h4>
			{map.failure && <p role="alert">{map.failure.message}</p>}
			{!map.data && !map.failure && (
				<p role="status">Loading patch addresses…</p>
			)}
			{map.data && (
				<>
					<p>
						Universe {map.data.universe}; {map.data.layerCount} layers;{" "}
						{map.data.channels.length} DMX slots. Addresses come from this
						running output’s decoder.
					</p>
					{map.data.layerCount !== 8 && (
						<p role="alert">
							This output is not configured for eight layers. Change Settings →
							DMX and restart before the eight-layer patch.
						</p>
					)}
					<table className="media-table">
						<caption>Suggested {output.name} patch</caption>
						<thead>
							<tr>
								<th>Head</th>
								<th>Universe</th>
								<th>Start address</th>
								<th>Last address</th>
								<th>Footprint</th>
							</tr>
						</thead>
						<tbody>
							{[...blocks].map(([label, addresses]) => (
								<tr key={label}>
									<td>{label}</td>
									<td>{map.data?.universe}</td>
									<td>{Math.min(...addresses)}</td>
									<td>{Math.max(...addresses)}</td>
									<td>{Math.max(...addresses) - Math.min(...addresses) + 1}</td>
								</tr>
							))}
						</tbody>
					</table>
				</>
			)}
		</section>
	);
}

