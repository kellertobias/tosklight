export function DmxPage() {
	const outputs = useOutputs();
	const telemetry = useTelemetry();
	const [connectOpen, setConnectOpen] = useState(false);

	return (
		<WindowFrame
			title="Diagnostics"
			className="media-dmx-window"
			info={{ primary: "DMX", secondary: "Input and channel diagnostics" }}
			groups={[
				{
					id: "dmx-diagnostics-actions",
					actions: [
						{
							id: "connect-console",
							label: "Connect to Console",
							variant: "primary",
							active: connectOpen,
							className: "media-connect-console",
							onPress: () => setConnectOpen((open) => !open),
						},
						{
							id: "configure-dmx-input",
							label: "Configure DMX input",
							onPress: () => {
								window.history.pushState(null, "", "/settings?section=dmx");
								window.dispatchEvent(new PopStateEvent("popstate"));
							},
						},
					],
				},
			]}
		>
			<section className="media-page media-dmx-content">
				{connectOpen && <ConsoleConnection outputs={outputs.data ?? []} />}
				<ResourceState
					resource={outputs}
					subject="outputs"
					isEmpty={(data) => data.length === 0}
					empty="This server has no enabled outputs, so nothing is listening for a desk."
				>
					{(data) =>
						data.map((output) => (
							<OutputDmx
								key={output.id}
								output={output}
								ingress={telemetry.frame?.dmx.find(
									(sample) => sample.outputId === output.id,
								)}
							/>
						))
					}
				</ResourceState>
			</section>
		</WindowFrame>
	);
}

function ConsoleConnection({ outputs }: { outputs: OutputView[] }) {
	const [consoleName, setConsoleName] = useState("MagicQ");
	const [fixtures, setFixtures] = useState<string[]>();
	const [failure, setFailure] = useState<string>();
	const network = useNetwork();
	useEffect(() => {
		let current = true;
		void api
			.fixtures()
			.then((names) => {
				if (current) setFixtures(names);
			})
			.catch((error: unknown) => {
				if (current) setFailure(String(error));
			});
		return () => {
			current = false;
		};
	}, []);
	const extension =
		consoleName === "MagicQ"
			? ".hed"
			: consoleName === "grandMA2"
				? ".xml"
				: ".gdtf";
	const files = fixtures?.filter((name) => name.endsWith(extension));
	return (
		<section className="media-settings-section" aria-label="Connect to Console">
			<h2>Connect to Console</h2>
			<label>
				Console{" "}
				<select
					value={consoleName}
					onChange={(event) => setConsoleName(event.target.value)}
				>
					{["MagicQ", "grandMA2", "grandMA3", "GDTF"].map((name) => (
						<option key={name}>{name}</option>
					))}
				</select>
			</label>
			<h3>{consoleName} personalities</h3>
			<p>
				These downloads are generated by this running Pixel server from its
				canonical DMX definition. Patch eight separate ToskLight Pixel Layer
				fixtures and one ToskLight Pixel Master fixture.
			</p>
			{!fixtures && !failure && (
				<p role="status">Loading generated personalities…</p>
			)}
			{failure && (
				<p role="alert">
					Could not load personalities: {failure}. Close and reopen Connect to
					Console to retry.
				</p>
			)}
			{files?.length === 0 && (
				<p role="alert">
					No generated personalities are available for this console.
				</p>
			)}
			<div className="media-settings-actions">
				{files?.map((name) => (
					<a
						className="ui-button ui-secondary ui-default"
						href={api.fixtureUrl(name)}
						download
						key={name}
					>
						Download {name}
					</a>
				))}
			</div>
			<h3>Configured footprint and patch addresses</h3>
			<p>
				Choose eight layers and Effect banks and full master controls in
				Settings → DMX. Apply pending changes by restarting Pixel before
				downloading and patching. Earlier channel layouts require migration to
				the full master layout for these generated personalities.
			</p>
			{outputs.length === 0 && (
				<p>No enabled outputs. Configure an output in Settings first.</p>
			)}
			{outputs.map((output) => (
				<ConsolePatch key={output.id} output={output} />
			))}
			<ConsoleTutorial consoleName={consoleName} />
			<ResourceState resource={network} subject="network settings">
				{(value) => (
					<>
						<h3>Active network listeners</h3>
						<dl className="media-facts">
							<dt>sACN (UDP)</dt>
							<dd>{value.resolved.sacnListen}</dd>
							<dt>Art-Net (UDP)</dt>
							<dd>{value.resolved.artNetListen}</dd>
							<dt>CITP/MSEX (TCP)</dt>
							<dd>
								{value.resolved.citpListen}; advertised port{" "}
								{value.citpAdvertisedPort}
							</dd>
							<dt>Pixel interface (HTTP)</dt>
							<dd>{value.resolved.httpListen}</dd>
						</dl>
						{value.pendingRestart && (
							<p role="alert">
								Network changes are pending. Restart Pixel before connecting.
							</p>
						)}
					</>
				)}
			</ResourceState>
		</section>
	);
}

